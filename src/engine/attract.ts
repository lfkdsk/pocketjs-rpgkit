// Button masks (contracts/spec/spec.ts BTN), duplicated as constants to
// keep this engine module free of framework imports.
const BTN_SELECT = 0x0001;
const BTN_UP = 0x0010;
const BTN_RIGHT = 0x0020;
const BTN_DOWN = 0x0040;
const BTN_LEFT = 0x0080;
const BTN_LTRIGGER = 0x0100;
const BTN_RTRIGGER = 0x0200;
const BTN_ZL = 0x0400;
const BTN_ZR = 0x0800;
const BTN_TRIANGLE = 0x1000;
/** The d-pad portion of a mask; a tick-direction resolver replaces only
 *  these bits between the timeline folds of one low-rate host frame. */
const BTN_DIR_MASK = BTN_UP | BTN_DOWN | BTN_LEFT | BTN_RIGHT;
const BTN_CIRCLE = 0x2000;
const BTN_CROSS = 0x4000;
const BTN_SQUARE = 0x8000;
const BTN_START = 0x0008;

/** The published tapes are generated by the deterministic 60 Hz journey
 *  drivers. A slower host consumes several of these source frames per host
 *  frame, keeping tape time and the complete reducer state rate-independent. */
export const ATTRACT_TAPE_HZ = 60;

/** A complete dialog remains readable for this many virtual seconds. Longer
 *  text earns up to one extra second before the tape may advance it. */
export const ATTRACT_READ_HOLD_MIN_SECONDS = 1.5;
export const ATTRACT_READ_HOLD_MAX_SECONDS = 2.5;
export const ATTRACT_READ_HOLD_CHARS_PER_SECOND = 120;

/** Ten minutes of 60 Hz input, exactly one u16 per folded source frame. */
export const ATTRACT_INPUT_LOG_FRAMES = ATTRACT_TAPE_HZ * 60 * 10;

/** One minute of the canonical 60 Hz source timeline. Display-only pacing
 * ticks do not advance this counter, so captures land on the same reducer
 * frame at every host rate. */
export const ATTRACT_KEYFRAME_INTERVAL_FRAMES = ATTRACT_TAPE_HZ * 60;

/** Default cap for the deterministic serialized-payload estimate retained by
 * rewind keyframes. Oldest keyframes are evicted first. A large game's state
 * serializes to tens of KiB, so this keeps a few minutes of keyframes while
 * the retained heap stays a small fraction of the game's own. */
export const ATTRACT_KEYFRAME_MAX_BYTES = 2 * 1024 * 1024;

/** Default cap on the number of retained rewind keyframes. */
export const ATTRACT_KEYFRAME_MAX_COUNT = 64;

const ALL_BUTTONS =
  BTN_SELECT | BTN_START | BTN_UP | BTN_RIGHT | BTN_DOWN | BTN_LEFT |
  BTN_LTRIGGER | BTN_RTRIGGER | BTN_ZL | BTN_ZR |
  BTN_TRIANGLE | BTN_CIRCLE | BTN_CROSS | BTN_SQUARE;

/** L and SELECT are transport controls. Every other defined button, including
 *  R/ZL/ZR, hands the current tape frame to the player. */
const TAKEOVER_KEYS = ALL_BUTTONS & ~(BTN_LTRIGGER | BTN_SELECT);

// Low five bits retain the reviewer-visible timeline flags; high three bits
// encode idle/typing/arming/reading/done as 0..4 for exact rewind restore.
const T_SOURCE = 1;
const T_HOLD = 2;
const T_END = 4;
const T_MODAL = 8;
const T_TYPE = 16;
const T_DISPLAY = T_HOLD | T_END | T_TYPE;
type PresentationStage = 0 | 1 | 2 | 3 | 4;

/** Demo presentation is one step below the authored 30 cps typewriter. */
export const ATTRACT_TYPEWRITER_CPS = 15;

export function attractReadHoldSeconds(chars: number): number {
  const weighted = ATTRACT_READ_HOLD_MIN_SECONDS + Math.max(0, chars) / ATTRACT_READ_HOLD_CHARS_PER_SECOND;
  return Math.min(ATTRACT_READ_HOLD_MAX_SECONDS, weighted);
}

export type AttractPhase = "attract" | "play";
export type AttractSpeed = 1 | 2 | 4;

export interface AttractOptions {
  immutableState?: boolean;
  /** Virtual frames per second; seconds-based timings derive from it. */
  hz: number;
  /** Source rate of the published tape. Defaults to 60 Hz. Tests that feed
   *  an adaptive tape generated at another rate set this explicitly. */
  tapeHz?: number;
  /** No-input frames before attract starts/restarts. Default 10 s. */
  idleFrames?: number;
  /** Source-timeline frames the victory state rests before a clean reset. */
  endHoldFrames?: number;
  /** Rewind distance in virtual seconds. Default 3. */
  rewindSeconds?: number;
  /** Reducer/source frames between periodic rewind keyframes. Defaults to
   *  3,600 (one minute at 60 Hz). Zero disables periodic captures; map and
   *  battle boundaries are still captured when the byte budget is nonzero. */
  keyframeIntervalFrames?: number;
  /** Maximum estimated payload bytes retained by rewind keyframes. Defaults
   *  to 2 MiB. Zero disables all keyframes and keeps the from-zero fallback. */
  keyframeMaxBytes?: number;
  /** Maximum number of retained keyframes, oldest evicted first. Defaults to
   *  64. Zero disables all keyframes. */
  keyframeMaxCount?: number;
  /** Grown-world play (examples/grow): never auto-enter attract from
   *  idle (the world was the demo itself; there is no tape to play).
   *  SELECT then invokes onSelect instead of handing control to a tape. */
  attractEnabled?: boolean;
  onSelect?: () => void;
  /** Required when project is a ProjectShell. Repository cache residency is
   * derived and never enters the rewind timeline. */
  maps?: MapRepository;
  /** Exact reviewed predecessor builds accepted for save loading. */
  compatibleSaveContent?: readonly MapContentVersion[];
  /** The same pure game registrations accepted by createSession(). They live
   * outside the rewind timeline; refolds reuse them against fresh state. */
  extensions?: ExtensionOptions;
  battle?: BattleRules;
  /** KG1: game-scene reducers keyed by id, forwarded to createSession. */
  scenes?: Record<string, SceneRules>;
  scene?: SceneOptions;
  /** Message pagination, forwarded to createSession (pure, like the
   *  registrations above). */
  paginateText?: TextPaginator;
  /** Resolver for `{x:<key>}` text tokens, forwarded to createSession (the
   *  same one GameView registers for live play, so a demo, a rewind and a
   *  re-fold expand text identically). Called once per token when a box
   *  opens; must be a pure function of the view. Only consulted when the
   *  project declares `system.textTokens`. */
  textTokens?: TextTokenResolver;
  /** Replay identity. Missing on a non-empty tape means legacy-transfer. */
  worldTraversal?: WorldTraversalMode;
  /** Optional connected-world opening resolver forwarded to Session. */
  handoff?: WorldHandoffResolver;
  /** Pure game policy for movement capabilities on trusted openings. */
  handoffCapability?: SessionOptions["handoffCapability"];
}

