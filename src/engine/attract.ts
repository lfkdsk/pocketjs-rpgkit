// src/engine/attract.ts — D1 attract mode + D2 takeover/rewind
// controller, folded over the same pure session reducer as live play
// (engine/session.ts).
//
// One principle governs the whole file: the reducer sees exactly ONE input
// stream, one u16 button mask per world frame. Demo and player frames are
// indistinguishable reducer inputs; the only difference is who chose the
// mask (the built-in tape or the live buttons). Display-only pacing ticks
// share the rewind timeline, but never call the reducer. That is why a
// paced demo visits the same world after every tape mask, takeover does not
// change the world, and rewind can restore both the world and the display.
//
//   idle N s with no input (boot or in play) -> attract starts from a
//            CLEAN reset, then loops the tape
//   attract: tape masks; after the final frame the world rests on the
//            victory state for holdFrames, then a clean reset to frame 0
//   any non-transport button during attract   -> takeover: that frame
//            still folds the tape mask (the world cannot jump), and from
//            the NEXT frame the live buttons drive; a "YOU HAVE CONTROL"
//            notice shows for two seconds
//   L (LTRIGGER)                             -> rewind 3 virtual seconds:
//            restore a retained keyframe and re-fold only the suffix
//   SELECT in play                           -> while the current frame is
//            still inside the tape prefix (or was rewound into it), the
//            demo resumes from exactly this frame; otherwise it restarts
//
// Rewind path: restore the nearest retained keyframe at or before the target,
// then run the ordinary reducer over only the suffix. Keyframes contain the
// complete JSON-shaped SessionState plus the controller's source/display
// cursors. A no-keyframe replay remains the reference path used by tests.
//
// Under SessionOptions.immutableState a published state is never written
// again, so a keyframe keeps the state itself instead of a deep copy: taking
// one allocates almost nothing and consecutive keyframes share every
// unchanged subtree. Without that contract keyframes stay deep copies.
// Either way the budget charges each keyframe its full serialized size, an
// upper bound on what a shared keyframe actually retains.

